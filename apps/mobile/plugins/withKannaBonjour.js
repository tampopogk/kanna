function withKannaBonjour(config) {
  config = withKannaAndroidBonjour(config);

  config = withInfoPlist(config, (config) => {
    config.modResults = applyInfoPlist(config.modResults);
    return config;
  });

  config = withDangerousMod(config, [
    "ios",
    (config) => {
      writeNativeSources(config.modRequest.projectRoot);
      const appDelegatePath = IOSConfig.Paths.getAppDelegateFilePath(
        config.modRequest.projectRoot
      );
      fs.writeFileSync(
        appDelegatePath,
        patchAppDelegate(fs.readFileSync(appDelegatePath, "utf8"))
      );
      return config;
    }
  ]);

  return withXcodeProject(config, (config) => {
    const projectRoot = config.modRequest.projectRoot;
    const projectName = IOSConfig.XcodeUtils.getProjectName(projectRoot);
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: `${projectName}/KannaBonjourModule.swift`,
      groupName: projectName,
      project: config.modResults
    });
    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: `${projectName}/KannaBonjourModule.m`,
      groupName: projectName,
      project: config.modResults
    });
    patchMetroPortScript(config.modResults);
    return config;
  });
}

function withKannaAndroidBonjour(config) {
  const packageName = config.android?.package;
  if (!packageName) {
    throw new Error("Kanna's Bonjour plugin needs android.package to generate its module.");
  }
  // A build that already permits cleartext everywhere (the dev identity, which
  // reaches a task-scoped server over the emulator host alias or an explicit
  // numeric URL) must keep that behavior: a network security config would
  // override `usesCleartextTraffic` and cut those hosts off.
  const scopedCleartext = config.android?.usesCleartextTraffic !== true;

  config = withDangerousMod(config, [
    "android",
    (config) => {
      writeAndroidSources(config.modRequest.projectRoot, packageName);
      if (scopedCleartext) {
        writeNetworkSecurityConfig(config.modRequest.projectRoot);
      }
      return config;
    }
  ]);

  config = withMainApplication(config, (config) => {
    config.modResults.contents = patchMainApplication(config.modResults.contents);
    return config;
  });

  if (!scopedCleartext) {
    return config;
  }

  return withAndroidManifest(config, (config) => {
    config.modResults = applyAndroidManifest(config.modResults);
    return config;
  });
}

