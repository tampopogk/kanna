function applyInfoPlist(plist) {
  const services = new Set(plist.NSBonjourServices || []);
  services.add(SERVICE_TYPE);

  return {
    ...plist,
    NSBonjourServices: Array.from(services),
    NSLocalNetworkUsageDescription: LOCAL_NETWORK_USAGE_DESCRIPTION
  };
}
