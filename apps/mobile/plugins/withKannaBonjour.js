/**
 * Shipped Android identities deny cleartext by default, but pairing and every
 * authenticated LAN read/stream talk http/ws to a desktop on the local network.
 * Permit cleartext for mDNS names only — that is the route discovery actually
 * produces — instead of turning it on for every destination.
 */
const NETWORK_SECURITY_CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/plugins/withKannaBonjour.js -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="true">local</domain>
    </domain-config>
</network-security-config>
`;

function patchMainApplication(contents) {
  if (contents.includes(ANDROID_PACKAGE_CLASS)) {
    return contents;
  }

  // Expo's current template builds the package list with `.apply { }` and a
  // commented example add; older shapes return the list directly or name it.
  const applyBlock = contents.replace(
    /PackageList\(this\)\.packages\.apply \{/,
    `PackageList(this).packages.apply {\n          add(${ANDROID_PACKAGE_CLASS}())`
  );
  if (applyBlock !== contents) {
    return applyBlock;
  }

  const inlineReturn = contents.replace(
    /return PackageList\(this\)\.packages\b/,
    `return PackageList(this).packages.apply {\n            add(${ANDROID_PACKAGE_CLASS}())\n          }`
  );
  if (inlineReturn !== contents) {
    return inlineReturn;
  }

  const listReturn = contents.replace(
    /(val packages = PackageList\(this\)\.packages[\s\S]*?)(\n(\s*)return packages\b)/,
    `$1\n$3packages.add(${ANDROID_PACKAGE_CLASS}())$2`
  );
  if (listReturn !== contents) {
    return listReturn;
  }

  throw new Error(
    "Unsupported Expo MainApplication template; could not register Kanna's Bonjour module."
  );
}

function applyAndroidManifest(manifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(manifest);
  application.$["android:networkSecurityConfig"] = `@xml/${NETWORK_SECURITY_CONFIG_RESOURCE}`;
  return manifest;
}

