/**
 * Android half of discovery. iOS browses with NetServiceBrowser; Android has no
 * equivalent of that framework, so this module drives the platform NsdManager
 * and emits the same `kannaBonjourServiceChanged` events, keeping one JS
 * browser (src/lib/discovery/bonjour.ts) for both platforms.
 */
function androidModuleSource(packageName) {
  return `package ${packageName}

import android.content.Context
import android.net.nsd.NsdManager
import android.net.nsd.NsdServiceInfo
import android.os.Build
import android.os.Handler
import android.os.Looper
import android.util.Log
import com.facebook.react.bridge.Arguments
import com.facebook.react.bridge.LifecycleEventListener
import com.facebook.react.bridge.Promise
import com.facebook.react.bridge.ReactApplicationContext
import com.facebook.react.bridge.ReactContextBaseJavaModule
import com.facebook.react.bridge.ReactMethod
import com.facebook.react.bridge.WritableMap
import java.net.Inet6Address
import java.net.InetAddress
import java.util.concurrent.Executor

/**
 * Generated by apps/mobile/plugins/withKannaBonjour.js. Edit the plugin, not
 * this file: prebuild overwrites it.
 *
 * Browses "_kanna-mobile._tcp" with the platform NsdManager and reports each
 * resolved desktop to JS in the same event shape KannaBonjourModule.swift uses.
 * Every piece of state below is owned by the main thread; NsdManager delivers
 * its callbacks on its own threads and React delivers method calls on the
 * native-modules thread, so both hop onto [mainHandler] first.
 */
class ${ANDROID_MODULE_NAME}(reactContext: ReactApplicationContext) :
  ReactContextBaseJavaModule(reactContext), LifecycleEventListener {

  private val mainHandler = Handler(Looper.getMainLooper())
  private val callbackExecutor = Executor { command -> mainHandler.post(command) }
  private val nsdManager: NsdManager? =
    reactContext.applicationContext.getSystemService(Context.NSD_SERVICE) as? NsdManager

  /** What JS asked for. Survives a foreground/background cycle. */
  private var browsingRequested = false
  private var discoveryListener: NsdManager.DiscoveryListener? = null
  private var discoveryActive = false

  /**
   * Fences callbacks belonging to a browse that has already been torn down.
   * NsdManager keeps delivering to a stopped listener until the platform
   * confirms the stop, and a late resolve would otherwise resurrect a desktop
   * that is no longer there.
   */
  private var browseGeneration = 0
  private val startPromises = mutableListOf<Promise>()
  private val serviceCallbacks = mutableMapOf<String, Any>()
  private val pendingResolves = ArrayDeque<NsdServiceInfo>()
  private var resolving = false

  init {
    reactContext.addLifecycleEventListener(this)
  }

  override fun getName(): String = NAME

  // NativeEventEmitter's bookkeeping. Kanna emits from native state, so these
  // only have to exist.
  @ReactMethod
  fun addListener(eventName: String) = Unit

  @ReactMethod
  fun removeListeners(count: Int) = Unit

  @ReactMethod
  fun startBrowsing() {
    mainHandler.post { startDiscovery(null) }
  }

  /**
   * Starts discovery and settles once the platform confirms the browse is
   * running, so a pairing attempt can tell "nothing is advertising" from "this
   * device cannot browse at all".
   */
  @ReactMethod
  fun ensureBrowsing(promise: Promise) {
    mainHandler.post {
      if (discoveryActive) {
        promise.resolve(null)
      } else {
        startDiscovery(promise)
      }
    }
  }

  @ReactMethod
  fun stopBrowsing() {
    mainHandler.post {
      browsingRequested = false
      stopDiscovery("Discovery stopped.")
    }
  }

  override fun onHostResume() {
    mainHandler.post {
      if (browsingRequested && discoveryListener == null) startDiscovery(null)
    }
  }

  override fun onHostPause() {
    mainHandler.post { stopDiscovery("The app left the foreground.") }
  }

  override fun onHostDestroy() {
    mainHandler.post {
      browsingRequested = false
      stopDiscovery("The app was destroyed.")
    }
  }

  override fun invalidate() {
    reactApplicationContext.removeLifecycleEventListener(this)
    mainHandler.post {
      browsingRequested = false
      stopDiscovery("The React instance went away.")
    }
    super.invalidate()
  }

  private fun startDiscovery(promise: Promise?) {
    browsingRequested = true
    val manager = nsdManager
    if (manager == null) {
      promise?.reject(ERROR_CODE, "This device does not support network service discovery.")
      return
    }
    if (promise != null) startPromises.add(promise)
    if (discoveryListener != null) return

    browseGeneration += 1
    val browse = browseGeneration
    val listener = object : NsdManager.DiscoveryListener {
      override fun onDiscoveryStarted(serviceType: String) = onMain(browse) {
        discoveryActive = true
        settleStartPromises(null)
      }

      override fun onStartDiscoveryFailed(serviceType: String, errorCode: Int) = onMain(browse) {
        discoveryListener = null
        discoveryActive = false
        settleStartPromises("Network service discovery could not start (code " + errorCode + ").")
      }

      override fun onDiscoveryStopped(serviceType: String) = onMain(browse) {
        discoveryActive = false
      }

      override fun onStopDiscoveryFailed(serviceType: String, errorCode: Int) = onMain(browse) {
        discoveryActive = false
      }

      override fun onServiceFound(serviceInfo: NsdServiceInfo) = onMain(browse) {
        trackService(serviceInfo, browse)
      }

      override fun onServiceLost(serviceInfo: NsdServiceInfo) = onMain(browse) {
        forgetService(serviceInfo.serviceName)
      }
    }
    discoveryListener = listener
    try {
      manager.discoverServices(DISCOVERY_SERVICE_TYPE, NsdManager.PROTOCOL_DNS_SD, listener)
    } catch (error: Throwable) {
      Log.w(NAME, "Could not browse for Kanna desktops.", error)
      discoveryListener = null
      discoveryActive = false
      settleStartPromises(error.message ?: "Network service discovery could not start.")
    }
  }

  private fun stopDiscovery(reason: String) {
    browseGeneration += 1
    discoveryActive = false
    settleStartPromises(reason)
    unregisterServiceCallbacks()
    pendingResolves.clear()
    resolving = false
    val manager = nsdManager
    val listener = discoveryListener
    discoveryListener = null
    if (manager == null || listener == null) return
    try {
      manager.stopServiceDiscovery(listener)
    } catch (error: Throwable) {
      // Already stopped by the platform; the generation fence drops whatever is
      // still in flight.
      Log.d(NAME, "Discovery was already stopped.", error)
    }
  }

  private fun settleStartPromises(error: String?) {
    if (startPromises.isEmpty()) return
    val promises = startPromises.toList()
    startPromises.clear()
    for (promise in promises) {
      if (error == null) promise.resolve(null) else promise.reject(ERROR_CODE, error)
    }
  }

  private fun trackService(serviceInfo: NsdServiceInfo, browse: Int) {
    val manager = nsdManager ?: return
    val name = serviceInfo.serviceName ?: return
    if (Build.VERSION.SDK_INT >= SERVICE_INFO_CALLBACK_SDK) {
      if (serviceCallbacks.containsKey(name)) return
      watchService(manager, serviceInfo, name, browse)
      return
    }
    // Older platforms resolve one service at a time; a second concurrent
    // resolve fails with "listener already in use".
    pendingResolves.addLast(serviceInfo)
    drainResolves(browse)
  }

  /**
   * API 34+ path. Kept in its own method so the callback class is only loaded
   * on platforms that have it.
   */
  private fun watchService(
    manager: NsdManager,
    serviceInfo: NsdServiceInfo,
    name: String,
    browse: Int
  ) {
    val callback = object : NsdManager.ServiceInfoCallback {
      override fun onServiceInfoCallbackRegistrationFailed(errorCode: Int) = onMain(browse) {
        serviceCallbacks.remove(name)
      }

      override fun onServiceUpdated(serviceInfo: NsdServiceInfo) = onMain(browse) {
        emitService(serviceInfo)
      }

      override fun onServiceLost() = onMain(browse) { forgetService(name) }

      override fun onServiceInfoCallbackUnregistered() = Unit
    }
    serviceCallbacks[name] = callback
    try {
      manager.registerServiceInfoCallback(serviceInfo, callbackExecutor, callback)
    } catch (error: Throwable) {
      Log.w(NAME, "Could not watch a discovered Kanna desktop.", error)
      serviceCallbacks.remove(name)
    }
  }

  private fun drainResolves(browse: Int) {
    if (resolving) return
    val manager = nsdManager ?: return
    val next = pendingResolves.removeFirstOrNull() ?: return
    resolving = true
    @Suppress("DEPRECATION")
    manager.resolveService(next, object : NsdManager.ResolveListener {
      override fun onResolveFailed(serviceInfo: NsdServiceInfo, errorCode: Int) = onMain(browse) {
        resolving = false
        drainResolves(browse)
      }

      override fun onServiceResolved(serviceInfo: NsdServiceInfo) = onMain(browse) {
        resolving = false
        emitService(serviceInfo)
        drainResolves(browse)
      }
    })
  }

  private fun unregisterServiceCallbacks() {
    if (serviceCallbacks.isEmpty()) return
    val callbacks = serviceCallbacks.values.toList()
    serviceCallbacks.clear()
    val manager = nsdManager ?: return
    if (Build.VERSION.SDK_INT < SERVICE_INFO_CALLBACK_SDK) return
    unregisterServiceInfoCallbacks(manager, callbacks)
  }

  private fun unregisterServiceInfoCallbacks(manager: NsdManager, callbacks: List<Any>) {
    for (callback in callbacks) {
      if (callback !is NsdManager.ServiceInfoCallback) continue
      try {
        manager.unregisterServiceInfoCallback(callback)
      } catch (error: Throwable) {
        Log.d(NAME, "A desktop watch was already unregistered.", error)
      }
    }
  }

  private fun forgetService(rawName: String?) {
    val name = rawName ?: return
    val callback = serviceCallbacks.remove(name)
    val manager = nsdManager
    if (callback != null && manager != null && Build.VERSION.SDK_INT >= SERVICE_INFO_CALLBACK_SDK) {
      unregisterServiceInfoCallbacks(manager, listOf(callback))
    }
    val event = Arguments.createMap()
    event.putString("name", name)
    event.putString("type", EVENT_SERVICE_TYPE)
    event.putBoolean("removed", true)
    emit(event)
  }

  private fun emitService(serviceInfo: NsdServiceInfo) {
    val host = resolveHost(serviceInfo)
    val port = serviceInfo.port
    if (host.isEmpty() || port <= 0) return

    val txt = Arguments.createMap()
    for (attribute in serviceInfo.attributes.entries) {
      val value = attribute.value
      txt.putString(attribute.key, if (value == null) "" else String(value, Charsets.UTF_8))
    }

    val event = Arguments.createMap()
    event.putString("name", serviceInfo.serviceName ?: "")
    event.putString("type", EVENT_SERVICE_TYPE)
    event.putString("host", host)
    event.putInt("port", port)
    event.putMap("txt", txt)
    event.putBoolean("removed", false)
    emit(event)
  }

  /**
   * Prefers the advertised mDNS hostname. Kanna's shipped Android builds permit
   * cleartext only for ".local", so a numeric address would be blocked by that
   * policy: a host that is not a resolvable ".local" name is a discovery fault
   * to fix, never a reason to widen the policy.
   */
  private fun resolveHost(serviceInfo: NsdServiceInfo): String {
    if (Build.VERSION.SDK_INT >= SERVICE_INFO_CALLBACK_SDK) {
      val hostname = normalizeHostname(serviceInfo.hostname)
      if (hostname.isNotEmpty()) {
        Log.d(NAME, "Resolved a Kanna desktop by its mDNS hostname.")
        return hostname
      }
    }
    val address = formatAddress(hostAddress(serviceInfo))
    if (address.isNotEmpty()) {
      // Shipped builds permit cleartext for ".local" only, so this desktop is
      // about to be unreachable. Say which half failed instead of leaving the
      // claim to fail silently.
      Log.w(NAME, "Resolved a Kanna desktop with no mDNS hostname.")
    }
    return address
  }

  private fun hostAddress(serviceInfo: NsdServiceInfo): InetAddress? {
    if (Build.VERSION.SDK_INT >= SERVICE_INFO_CALLBACK_SDK) {
      val addresses = serviceInfo.hostAddresses
      return addresses.firstOrNull { address -> address !is Inet6Address }
        ?: addresses.firstOrNull()
    }
    @Suppress("DEPRECATION")
    return serviceInfo.host
  }

  private fun normalizeHostname(rawHostname: String?): String {
    val hostname = rawHostname?.trim()?.trimEnd('.').orEmpty()
    if (hostname.isEmpty()) return ""
    return if (hostname.contains('.')) hostname else hostname + ".local"
  }

  private fun formatAddress(address: InetAddress?): String {
    val raw = address?.hostAddress?.substringBefore('%').orEmpty()
    if (raw.isEmpty()) return ""
    return if (address is Inet6Address) "[" + raw + "]" else raw
  }

  private fun emit(event: WritableMap) {
    val context = reactApplicationContext
    if (!context.hasActiveReactInstance()) return
    context.emitDeviceEvent(EVENT_NAME, event)
  }

  private fun onMain(browse: Int, body: () -> Unit) {
    mainHandler.post { if (browse == browseGeneration) body() }
  }

  companion object {
    const val NAME = "${ANDROID_MODULE_NAME}"
    private const val EVENT_NAME = "kannaBonjourServiceChanged"
    private const val DISCOVERY_SERVICE_TYPE = "${SERVICE_TYPE}"
    /** iOS reports the resolved type with its trailing dot; match it. */
    private const val EVENT_SERVICE_TYPE = "${SERVICE_TYPE}."
    private const val ERROR_CODE = "kanna_bonjour_unavailable"
    /** NsdManager.ServiceInfoCallback, and NsdServiceInfo.getHostname(). */
    private const val SERVICE_INFO_CALLBACK_SDK = 34
  }
}
`;
}

